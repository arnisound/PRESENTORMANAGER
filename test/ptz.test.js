import { test } from 'node:test';
import assert from 'node:assert/strict';
import { visca } from '../server/ptz.js';

test('VISCA : trames pan / tilt, zoom, préréglages', () => {
  assert.deepEqual(visca.move(-1, 1), [0x81, 0x01, 0x06, 0x01, 0x18, 0x14, 0x01, 0x01, 0xff]);
  assert.deepEqual(visca.move(0, 0).slice(6, 8), [0x03, 0x03]);
  assert.deepEqual(visca.move(0.5, -0.5).slice(4, 8), [12, 10, 0x02, 0x02]);
  assert.deepEqual(visca.zoom(1), [0x81, 0x01, 0x04, 0x07, 0x27, 0xff]);
  assert.deepEqual(visca.zoom(-0.5), [0x81, 0x01, 0x04, 0x07, 0x34, 0xff]);
  assert.deepEqual(visca.zoom(0), [0x81, 0x01, 0x04, 0x07, 0x00, 0xff]);
  assert.deepEqual(visca.recall(3), [0x81, 0x01, 0x04, 0x3f, 0x02, 0x03, 0xff]);
  assert.deepEqual(visca.store(3), [0x81, 0x01, 0x04, 0x3f, 0x01, 0x03, 0xff]);
});
